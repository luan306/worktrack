// → mỗi người chỉ tải đúng ngôn ngữ mình dùng (bundle nhẹ hơn ~2/3 phần chữ)
const LOADERS = { ja: () => import('./ja.js'), vi: () => import('./vi.js') };
const lazyLangs = {
  type: 'backend',
  init() {},
  read(lng, ns, cb) {
    if (lng === 'en') return cb(null, en);
    const load = LOADERS[lng];
    if (!load) return cb(null, {});
    load().then(m => cb(null, m.default), e => cb(e, null));
  },
};

let saved = 'en';
try { saved = localStorage.getItem('lang') || 'en'; } catch { /* trình duyệt chặn lưu */ }

// main.jsx đợi promise này rồi mới vẽ → không nháy chữ tiếng Anh khi đang dùng tiếng Việt
export const i18nReady = i18n.use(lazyLangs).use(initReactI18next).init({
  resources: { en: { translation: en } },
  partialBundledLanguages: true,
  lng: saved,
  fallbackLng: 'en',
  interpolation: { escapeValue: false },
  react: { useSuspense: false }, // tránh màn chờ Suspense khi đổi ngôn ngữ
});

export default i18n;
